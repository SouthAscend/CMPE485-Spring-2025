def graph_stagger_table(table_data, name):
    ratios = [0.05, 0.10, 0.25, 0.50, 1.00]
    Ns = sorted(table_data.keys())

    # compute averages
    avg = {N: {r: np.mean(table_data[N][r]) for r in ratios} for N in Ns}

    # plot
    plt.figure(figsize=(8,5))

    for r in ratios:
        plt.plot(Ns, [avg[N][r] for N in Ns], 'o-', label=f'R={r:.2f}')

    plt.xscale('log')
    plt.yscale('log')

    # ⇣ turn off scientific 10^n notation
    plt.gca().xaxis.set_major_formatter(ScalarFormatter())
    plt.gca().yaxis.set_major_formatter(ScalarFormatter())
    plt.gca().xaxis.set_minor_formatter(ScalarFormatter())
    plt.gca().yaxis.set_minor_formatter(ScalarFormatter())

    plt.xlabel('Agents per team (N)')
    plt.ylabel('Average FPS')
    plt.title('Average FPS vs N for different stagger ratios for ' + name + ' range')
    plt.grid(True, which='both', alpha=.3)
    plt.legend()
    plt.tight_layout()
    plt.show()

def compare_ranges_for_ratio(ratio):
    Ns = sorted(data.keys())

    avg_normal = [np.mean(data[N][ratio]) for N in Ns]
    avg_small = [np.mean(small_range_data[N][ratio]) for N in Ns]
    avg_large = [np.mean(large_range_data[N][ratio]) for N in Ns]

    plt.figure(figsize=(8, 5))
    plt.plot(Ns, avg_normal, 'o-', label='Normal Range')
    plt.plot(Ns, avg_small, 's-', label='Small Range')
    plt.plot(Ns, avg_large, '^-', label='Large Range')

    plt.xscale('log')
    plt.yscale('log')

    plt.gca().xaxis.set_major_formatter(ScalarFormatter())
    plt.gca().yaxis.set_major_formatter(ScalarFormatter())
    plt.gca().xaxis.set_minor_formatter(ScalarFormatter())
    plt.gca().yaxis.set_minor_formatter(ScalarFormatter())

    plt.xlabel('Agents per team (N)')
    plt.ylabel('Average FPS')
    plt.title(f'Range comparison at R={ratio}')
    plt.grid(True, which='both', alpha=0.3)
    plt.legend()
    plt.tight_layout()
    plt.show()


